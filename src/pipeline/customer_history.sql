USE CATALOG IDENTIFIER(:catalog);
USE SCHEMA bronze;

CREATE OR REFRESH STREAMING TABLE silver.customer_versions
COMMENT 'Grain: customer_key and segment validity interval, generated by AUTO CDC.';

CREATE FLOW customer_cdc AS AUTO CDC INTO silver.customer_versions
FROM STREAM(silver.customer_events)
KEYS (customer_key)
SEQUENCE BY effective_date
COLUMNS * EXCEPT (effective_date, _source_file, _batch_id)
STORED AS SCD TYPE 2
TRACK HISTORY ON market_segment;
